import AppKit
import LinkPresentation
import Network
import Observation
import UniformTypeIdentifiers
import Vision

@MainActor
@Observable
final class ClipboardHistory {
    /// Bumped whenever history changes so views reading `search` refresh.
    private(set) var revision = 0

    @ObservationIgnored let store: ClipboardStore?
    /// Called with every item changed on this Mac.
    @ObservationIgnored var onLocalChange: (SyncItem) -> Void = { _ in }
    /// Called with the iCloud record name of every synced item deleted on this Mac.
    @ObservationIgnored var onLocalDelete: (String) -> Void = { _ in }
    /// How long unpinned items are kept; shortening it removes older items right away.
    var retention = ClipboardRetention(rawValue: UserDefaults.standard.string(forKey: "clipboardRetention") ?? "") ?? .forever {
        didSet {
            UserDefaults.standard.set(retention.rawValue, forKey: "clipboardRetention")
            pruneExpiredItems()
        }
    }
    /// Whether copied links get their page's title and preview image. Fetching opens the link, so it can be turned off.
    var fetchesLinkPreviews = UserDefaults.standard.object(forKey: "clipboardFetchesLinkPreviews") as? Bool ?? true {
        didSet {
            UserDefaults.standard.set(fetchesLinkPreviews, forKey: "clipboardFetchesLinkPreviews")
            fetchPendingLinkPreviews()
        }
    }
    /// Bundle identifiers of apps whose copies are never saved.
    var ignoredApps = UserDefaults.standard.stringArray(forKey: "clipboardIgnoredApps") ?? [] {
        didSet { UserDefaults.standard.set(ignoredApps, forKey: "clipboardIgnoredApps") }
    }

    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    /// Hashing, PNG encoding and database writes run here, in copy order, so the main thread never waits on them.
    @ObservationIgnored private let recordingQueue = DispatchQueue(label: "codes.dibble.whippet.clipboard", qos: .userInitiated)
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var isRecognizing = false
    @ObservationIgnored private var isFetchingPreviews = false
    /// Previews wait while the Mac is offline, rather than marking every link as having none.
    @ObservationIgnored private let pathMonitor = NWPathMonitor()
    @ObservationIgnored private var isOnline = true

    private static let resultLimit = 100
    /// Larger text copies aren't saved: they're slow to show, and too big for an iCloud record.
    static let maximumTextBytes = 500_000

    /// Password managers mark secrets with these types (see nspasteboard.org), so they never enter history.
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    init() {
        do {
            store = try ClipboardStore()
        } catch {
            NSLog("Clipboard history disabled: \(error)")
            store = nil
        }
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        recognizePendingImages()
        pruneExpiredItems()
        pathMonitor.pathUpdateHandler = { [weak self] path in
            let isOnline = path.status == .satisfied
            Task { @MainActor in
                guard let self else { return }
                self.isOnline = isOnline
                self.fetchPendingLinkPreviews()
            }
        }
        pathMonitor.start(queue: .main)
    }

    func search(_ query: String, kind: ClipboardKind?) -> [ClipboardItem] {
        _ = revision
        return (try? store?.search(query, kind: kind, limit: Self.resultLimit)) ?? []
    }

    func imageURL(for item: ClipboardItem) -> URL? {
        store?.imageURL(for: item)
    }

    func usage() -> ClipboardUsage? {
        try? store?.usage()
    }

    func setPinned(_ pinned: Bool, item: ClipboardItem) {
        do {
            if let syncItem = try store?.setPinned(pinned, id: item.id) {
                onLocalChange(syncItem)
            }
            revision += 1
        } catch {
            NSLog("Failed to pin clipboard item: \(error)")
        }
    }

    func delete(_ item: ClipboardItem) {
        do {
            if let recordName = try store?.delete(contentHash: item.contentHash) {
                onLocalDelete(recordName)
            }
            revision += 1
        } catch {
            NSLog("Failed to delete clipboard item: \(error)")
        }
    }

    /// Refreshes views after another Mac's changes were merged into the store, which may include items past retention.
    /// Links from other Macs get their previews here.
    func didMergeRemoteChanges() {
        revision += 1
        pruneExpiredItems()
        fetchPendingLinkPreviews()
    }

    /// Fetches a link's preview again.
    func refreshPreview(_ item: ClipboardItem) {
        guard item.kind == .link else { return }
        try? store?.clearLinkPreview(hash: item.contentHash)
        revision += 1
        fetchPendingLinkPreviews()
    }

    /// Deletes unpinned items, or every item with `includingPinned`, here and from iCloud.
    func clear(includingPinned: Bool) {
        deleteItems { try $0.deleteItems(copiedBefore: nil, includingPinned: includingPinned) }
    }

    private func pruneExpiredItems() {
        guard let cutoff = retention.cutoff(from: .now) else { return }
        deleteItems { try $0.deleteItems(copiedBefore: cutoff) }
    }

    private func deleteItems(_ delete: @escaping @Sendable (ClipboardStore) throws -> [String]) {
        guard let store else { return }
        recordingQueue.async { [weak self] in
            do {
                let recordNames = try delete(store)
                Task { @MainActor in
                    guard let self else { return }
                    recordNames.forEach(self.onLocalDelete)
                    self.revision += 1
                }
            } catch {
                NSLog("Failed to delete clipboard items: \(error)")
            }
        }
    }

    /// Puts the item on the pasteboard, or leaves the pasteboard alone and returns false when an image's file is
    /// missing or unreadable. Images go on as the stored PNG, with TIFF for apps that only read that.
    @discardableResult
    func copy(_ item: ClipboardItem) -> Bool {
        let pasteboard = NSPasteboard.general
        if item.kind == .image {
            guard let file = imageURL(for: item), let png = try? Data(contentsOf: file) else { return false }
            let pasteboardItem = NSPasteboardItem()
            pasteboardItem.setData(png, forType: .png)
            if let tiff = NSImage(data: png)?.tiffRepresentation {
                pasteboardItem.setData(tiff, forType: .tiff)
            }
            pasteboard.clearContents()
            pasteboard.writeObjects([pasteboardItem])
        } else {
            pasteboard.clearContents()
            pasteboard.setString(item.text ?? "", forType: .string)
        }
        // Polling would record the copy again, and a re-encoded image as a duplicate, so the item moves to the top here
        // instead.
        lastChangeCount = pasteboard.changeCount
        let contentHash = item.contentHash
        record { try $0.recordCopy(contentHash: contentHash) }
        return true
    }

    func recordCalculation(expression: String, answer: String, isRPN: Bool) {
        do {
            if let syncItem = try store?.recordCalculation(expression: expression, answer: answer, mode: isRPN ? "rpn" : "standard") {
                onLocalChange(syncItem)
            }
            revision += 1
        } catch {
            NSLog("Failed to record calculation: \(error)")
        }
    }

    func recentCalculations(limit: Int) -> [CalculationRecord] {
        _ = revision
        return (try? store?.recentCalculations(limit: limit)) ?? []
    }

    func copy(text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        if let types = pasteboard.types, !Self.skippedTypes.isDisjoint(with: types) { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let source, ignoredApps.contains(source) { return }

        // The pasteboard is read here; the slow work happens on the recording queue.
        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            guard text.utf8.count <= Self.maximumTextBytes else { return }
            record { try $0.recordText(text, sourceBundleID: source) }
            return
        }
        guard let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) else { return }
        record(recognizesText: true) { store in
            guard
                let bitmap = NSBitmapImageRep(data: data),
                let png = bitmap.representation(using: .png, properties: [:])
            else { return nil }
            return try store.recordImage(png: png, width: bitmap.pixelsWide, height: bitmap.pixelsHigh, sourceBundleID: source)
        }
    }

    private func record(recognizesText: Bool = false, _ save: @escaping @Sendable (ClipboardStore) throws -> SyncItem?) {
        guard let store else { return }
        let cutoff = retention.cutoff(from: .now)
        recordingQueue.async { [weak self] in
            do {
                guard let item = try save(store) else { return }
                // Each copy is a chance to remove what has expired since, without a timer.
                let expired = try cutoff.map { try store.deleteItems(copiedBefore: $0) } ?? []
                Task { @MainActor in
                    guard let self else { return }
                    self.onLocalChange(item)
                    expired.forEach(self.onLocalDelete)
                    self.revision += 1
                    if recognizesText {
                        self.recognizePendingImages()
                    }
                    self.fetchPendingLinkPreviews()
                }
            } catch {
                NSLog("Failed to record clipboard item: \(error)")
            }
        }
    }

    /// Works through unrecognized images one at a time, newest first, including any left over from a previous launch.
    private func recognizePendingImages() {
        guard !isRecognizing, let store else { return }
        isRecognizing = true
        Task {
            while let pending = try? store.nextImageAwaitingRecognition() {
                let text = await Task.detached(priority: .utility) { Self.recognizeText(in: pending.file) }.value
                if pending.isLinkPreview {
                    guard (try? store.setLinkPreviewRecognizedText(text, hash: pending.hash)) != nil else { break }
                } else {
                    guard let syncItem = try? store.setRecognizedText(text, hash: pending.hash) else { break }
                    onLocalChange(syncItem)
                }
                revision += 1
            }
            isRecognizing = false
        }
    }

    /// Works through links without a preview one at a time, newest first, including links copied before previews
    /// existed. A link that can't be fetched is saved with no title, so it isn't tried again until Refresh Preview.
    private func fetchPendingLinkPreviews() {
        guard fetchesLinkPreviews, isOnline, !isFetchingPreviews, let store else { return }
        isFetchingPreviews = true
        Task {
            while fetchesLinkPreviews, isOnline, let pending = try? store.nextLinkAwaitingPreview() {
                let preview = await Self.fetchPreview(of: pending.url)
                // Gone offline mid-fetch: the link waits until the Mac is back online.
                guard isOnline else { break }
                guard (try? store.setLinkPreview(title: preview.title, imagePNG: preview.png, hash: pending.hash)) != nil
                else { break }
                revision += 1
                if preview.png != nil {
                    recognizePendingImages()
                }
            }
            isFetchingPreviews = false
        }
    }

    nonisolated private static let previewTimeout: TimeInterval = 15
    /// Preview images are only shown in the history's detail pane, so they're kept no larger than this.
    nonisolated private static let previewMaxPixelSize = 1200

    /// The page's title and its preview image, or the site's icon, as PNG. Fails quietly with an empty title.
    nonisolated private static func fetchPreview(of url: URL) async -> (title: String, png: Data?) {
        let provider = LPMetadataProvider()
        provider.timeout = previewTimeout
        guard let metadata = try? await provider.startFetchingMetadata(for: url) else { return ("", nil) }
        let title = metadata.title?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        guard let imageProvider = metadata.imageProvider ?? metadata.iconProvider else { return (title, nil) }
        let data: Data? = await withCheckedContinuation { continuation in
            imageProvider.loadDataRepresentation(forTypeIdentifier: UTType.image.identifier) { data, _ in
                continuation.resume(returning: data)
            }
        }
        return (title, data.flatMap(downscaledPNG))
    }

    nonisolated private static func downscaledPNG(_ data: Data) -> Data? {
        let options = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: previewMaxPixelSize,
        ] as CFDictionary
        guard
            let source = CGImageSourceCreateWithData(data as CFData, nil),
            let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options)
        else { return nil }
        return NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:])
    }

    nonisolated private static func recognizeText(in file: URL) -> String {
        let request = VNRecognizeTextRequest()
        request.recognitionLevel = .accurate
        request.automaticallyDetectsLanguage = true
        request.usesLanguageCorrection = true
        try? VNImageRequestHandler(url: file).perform([request])
        return (request.results ?? [])
            .compactMap { $0.topCandidates(1).first?.string }
            .joined(separator: "\n")
    }
}
