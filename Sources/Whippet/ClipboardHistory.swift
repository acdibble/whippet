import AppKit
import Observation
import Vision

@MainActor
@Observable
final class ClipboardHistory {
    /// Bumped whenever history changes so views reading `search` refresh.
    private(set) var revision = 0

    @ObservationIgnored let store: ClipboardStore?
    /// Called with the sync record name of every item changed on this Mac.
    @ObservationIgnored var onLocalChange: (String) -> Void = { _ in }
    /// Called with the sync record name of every item deleted on this Mac.
    @ObservationIgnored var onLocalDelete: (String) -> Void = { _ in }
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var isRecognizing = false

    private static let resultLimit = 100

    /// Password managers mark secrets with these types (see nspasteboard.org), so they never enter history.
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    init() {
        do {
            store = try ClipboardStore()
        } catch {
            NSLog("Clipboard history disabled: \(error)")
            store = nil
        }
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        recognizePendingImages()
    }

    func search(_ query: String, kind: ClipboardKind?) -> [ClipboardItem] {
        _ = revision
        return (try? store?.search(query, kind: kind, limit: Self.resultLimit)) ?? []
    }

    func imageURL(for item: ClipboardItem) -> URL? {
        store?.imageURL(for: item)
    }

    func usage() -> ClipboardUsage? {
        try? store?.usage()
    }

    func setPinned(_ pinned: Bool, item: ClipboardItem) {
        do {
            if let recordName = try store?.setPinned(pinned, id: item.id) {
                onLocalChange(recordName)
            }
            revision += 1
        } catch {
            NSLog("Failed to pin clipboard item: \(error)")
        }
    }

    func delete(_ item: ClipboardItem) {
        let recordName = ClipboardStore.clipboardRecordName(item.contentHash)
        do {
            try store?.deleteRecord(named: recordName)
            onLocalDelete(recordName)
            revision += 1
        } catch {
            NSLog("Failed to delete clipboard item: \(error)")
        }
    }

    /// Refreshes views after another Mac's changes were merged into the store.
    func didMergeRemoteChanges() {
        revision += 1
    }

    func copy(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        if let file = imageURL(for: item), let image = NSImage(contentsOf: file) {
            pasteboard.writeObjects([image])
            return
        }
        pasteboard.setString(item.text ?? "", forType: .string)
    }

    func recordCalculation(expression: String, answer: String, isRPN: Bool) {
        do {
            try store?.recordCalculation(expression: expression, answer: answer, mode: isRPN ? "rpn" : "standard")
            revision += 1
        } catch {
            NSLog("Failed to record calculation: \(error)")
        }
    }

    func recentCalculations(limit: Int) -> [CalculationRecord] {
        _ = revision
        return (try? store?.recentCalculations(limit: limit)) ?? []
    }

    func copy(text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        if let types = pasteboard.types, !Self.skippedTypes.isDisjoint(with: types) { return }
        guard let store else { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        do {
            if let text = pasteboard.string(forType: .string), !text.isEmpty {
                onLocalChange(try store.recordText(text, sourceBundleID: source))
                revision += 1
                return
            }
            guard
                let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
                let bitmap = NSBitmapImageRep(data: data),
                let png = bitmap.representation(using: .png, properties: [:])
            else { return }
            onLocalChange(try store.recordImage(png: png, width: bitmap.pixelsWide, height: bitmap.pixelsHigh, sourceBundleID: source))
            revision += 1
            recognizePendingImages()
        } catch {
            NSLog("Failed to record clipboard item: \(error)")
        }
    }

    /// Works through unrecognized images one at a time, newest first, including any left over from a previous launch.
    private func recognizePendingImages() {
        guard !isRecognizing, let store else { return }
        isRecognizing = true
        Task {
            while let pending = try? store.nextImageAwaitingRecognition() {
                let text = await Task.detached(priority: .utility) { Self.recognizeText(in: pending.file) }.value
                guard let recordName = try? store.setRecognizedText(text, hash: pending.hash) else { break }
                onLocalChange(recordName)
                revision += 1
            }
            isRecognizing = false
        }
    }

    nonisolated private static func recognizeText(in file: URL) -> String {
        let request = VNRecognizeTextRequest()
        request.recognitionLevel = .accurate
        request.automaticallyDetectsLanguage = true
        request.usesLanguageCorrection = true
        try? VNImageRequestHandler(url: file).perform([request])
        return (request.results ?? [])
            .compactMap { $0.topCandidates(1).first?.string }
            .joined(separator: "\n")
    }
}
